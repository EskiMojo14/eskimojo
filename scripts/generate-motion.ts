/**
 * Generates src/shared/styles/motion/springs.gen.css: Material 3 spring motion tokens as CSS
 * linear() easings plus settle durations.
 *
 * The damping ratios and stiffnesses are copied from Compose Material 3's
 * StandardMotionTokens.kt and ExpressiveMotionTokens.kt. Each spring is solved
 * analytically (mass 1, starting at rest), its duration is the time it takes to stay
 * within `settleThreshold` of the target, and the curve is sampled and simplified.
 */
import { writeFormatted } from "./write-formatted.ts";

type Spring = { damping: number; stiffness: number };
type Speed = "fast" | "default" | "slow";

const schemes: Record<"standard" | "expressive", Record<Speed, Spring>> = {
  standard: {
    fast: { damping: 0.9, stiffness: 1400 },
    default: { damping: 0.9, stiffness: 700 },
    slow: { damping: 0.9, stiffness: 300 },
  },
  expressive: {
    fast: { damping: 0.6, stiffness: 800 },
    default: { damping: 0.8, stiffness: 380 },
    slow: { damping: 0.8, stiffness: 200 },
  },
};

// Effects springs never overshoot and are the same in both schemes.
const effects: Record<Speed, Spring> = {
  fast: { damping: 1, stiffness: 3800 },
  default: { damping: 1, stiffness: 1600 },
  slow: { damping: 1, stiffness: 800 },
};

/** How close to the target (as a fraction of the distance) counts as settled. */
const settleThreshold = 0.001;
/** Maximum error allowed when dropping points from the sampled curve. */
const tolerance = 0.002;
const samples = 200;

/** Progress (0 at rest → 1 at the target) after t seconds. */
function position({ damping: z, stiffness }: Spring, t: number): number {
  const w0 = Math.sqrt(stiffness);
  if (z >= 1) {
    return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
  }
  const wd = w0 * Math.sqrt(1 - z * z);
  return 1 - Math.exp(-z * w0 * t) * (Math.cos(wd * t) + ((z * w0) / wd) * Math.sin(wd * t));
}

/** Seconds until the spring stays within settleThreshold of the target. */
function settleTime(spring: Spring): number {
  const step = 0.0005;
  let lastOutside = 0;
  for (let t = 0; t < 5; t += step) {
    if (Math.abs(1 - position(spring, t)) > settleThreshold) lastOutside = t;
  }
  return lastOutside + step;
}

type Point = [x: number, y: number];

/** Ramer–Douglas–Peucker: drop points that linear interpolation reproduces within tolerance. */
function simplify(points: Point[]): Point[] {
  if (points.length < 3) return points;
  const [x0, y0] = points[0];
  const [x1, y1] = points[points.length - 1];
  let maxError = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const error = Math.abs(y - (y0 + ((y1 - y0) * (x - x0)) / (x1 - x0)));
    if (error > maxError) {
      maxError = error;
      index = i;
    }
  }
  if (maxError <= tolerance) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}

const round = (n: number, digits: number) => Number(n.toFixed(digits));

function toCss(spring: Spring): { easing: string; duration: string } {
  const duration = settleTime(spring);
  const points: Point[] = Array.from({ length: samples + 1 }, (_, i) => {
    const x = i / samples;
    return [x, i === samples ? 1 : position(spring, x * duration)];
  });
  const stops = simplify(points).map(([x, y], i, all) =>
    i === 0 || i === all.length - 1 ? `${round(y, 3)}` : `${round(y, 3)} ${round(x * 100, 1)}%`,
  );
  return {
    easing: `linear(${stops.join(", ")})`,
    duration: `${Math.round(duration * 1000)}ms`,
  };
}

const describe = ({ damping, stiffness }: Spring) => `damping ${damping}, stiffness ${stiffness}`;

function declarations(type: "spatial" | "effects", speeds: Record<Speed, Spring>) {
  return Object.entries(speeds).flatMap(([speed, params]) => {
    const { easing, duration } = toCss(params);
    const name = `--md-sys-motion-spring-${speed}-${type}`;
    return [
      `  /* ${describe(params)} */`,
      `  ${name}: ${easing};`,
      `  ${name}-duration: ${duration};`,
    ];
  });
}

const blocks = [
  ...Object.entries(schemes).map(
    ([scheme, speeds]) => `%motion-${scheme} {\n${declarations("spatial", speeds).join("\n")}\n}`,
  ),
  `:root {\n${declarations("effects", effects).join("\n")}\n}`,
];

const out = new URL("../src/shared/styles/motion/springs.gen.css", import.meta.url);
await writeFormatted(
  out,
  `/* Generated by scripts/generate-motion.ts — do not edit by hand. */\n\n${blocks.join("\n\n")}\n`,
);
